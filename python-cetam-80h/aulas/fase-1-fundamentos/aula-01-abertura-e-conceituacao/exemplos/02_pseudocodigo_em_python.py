# Aula 01 | Do pseudocódigo ao código: custo de um passeio de barco.

# Pseudocódigo:
# 1. Leia o preço do passeio por pessoa
# 2. Leia o número de pessoas
# 3. Calcule: custo_total = preço × pessoas
# 4. Mostre o custo_total

preco_por_pessoa = 85.00
pessoas = 4
custo_total = preco_por_pessoa * pessoas
print("Custo total do passeio:", custo_total)
